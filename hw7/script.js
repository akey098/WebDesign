function setLanguage(lang) {
  if (!Object.hasOwn(translations, lang)) return;
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll('[data-i18n]')) {
    const key = el.dataset.i18n;
    if (!Object.hasOwn(translations[lang], key)) continue;
    if (key === 'heroTitle') el.innerHTML = translations[lang][key];
    else el.textContent = translations[lang][key];
  }
  document.querySelectorAll('[data-lang]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  document.title = `MercyMed | ${lang === 'ru' ? 'Забота о вашем здоровье' : lang === 'ky' ? 'Ден соолугуңузга кам көрүү' : 'Care that puts people first'}`;
  try { localStorage.setItem('mercymed-language', lang); } catch (_) {}
}
