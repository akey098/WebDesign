const bookingOpen = document.getElementById('whatsapp-demo');
const bookingCopy = document.getElementById('booking-copy');
const bookingCopyStatus = document.getElementById('booking-copy-status');
let requestedService = null;
function bookingDraft() {
  const language = document.documentElement.lang || 'en';
  const serviceName = requestedService ? translations[language][requestedService] : null;
  if (language === 'ru') return 'Здравствуйте, MercyMed! Хочу узнать о записи' + (serviceName ? ' по направлению «' + serviceName + '»' : '') + '. Пожалуйста, подскажите доступные варианты. [Учебный прототип — это не реальная запись.]';
  if (language === 'ky') return 'Саламатсызбы, MercyMed! Кабыл алууга жазылуу' + (serviceName ? ' (' + serviceName + ')' : '') + ' жөнүндө маалымат алгым келет. Жеткиликтүү убакыттарды айтып бериңиз. [Окуу прототиби — чыныгы жазылуу эмес.]';
  return 'Hello MercyMed! I would like to ask about an appointment' + (serviceName ? ' for ' + serviceName.toLowerCase() : '') + '. Could you please share availability? [Student prototype only — not a real booking.]';
}
function refreshBookingMessage() {
  const message = bookingDraft();
  bookingMessage.textContent = message;
  // No destination phone is specified: show the WhatsApp sharing flow instead of a fake clinic chat.
  bookingOpen.href = 'https://api.whatsapp.com/send?text=' + encodeURIComponent(message);
}
document.querySelectorAll('[data-booking]').forEach(link => link.addEventListener('click', event => {
  event.preventDefault();
  requestedService = link.dataset.service || null;
  refreshBookingMessage();
  if (typeof bookingDialog.showModal === 'function') bookingDialog.showModal();
  else bookingDialog.setAttribute('open', '');
}));
